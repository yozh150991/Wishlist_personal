import { useEffect } from 'react';
import { useI18n } from './i18n';

/**
 * Заголовок вкладки, поки жоден екран не назвав себе: той самий рядок, що й
 * статичний `<title>` в `index.html`. Назва продукту не перекладається.
 */
export const APP_TITLE = 'Wishlist';

/**
 * «<Назва екрана> · Wishlist», а без назви екрана — просто «Wishlist».
 *
 * Окрема чиста функція, щоб формат жив в одному місці й перевірявся без
 * браузера.
 */
export function documentTitle(screen: string | null | undefined, app: string = APP_TITLE): string {
  const name = screen?.trim();
  return name ? `${name} · ${app}` : app;
}

/**
 * Заголовок вкладки для екрана (аудит A-7: раніше всюди було «Wishlist», і
 * вкладки в перемикачі, історія браузера й зчитувач екрана не розрізняли
 * сторінок).
 *
 * Викликає кожен екран із таблиці маршрутів (`designs/v2/RoutesV2.tsx`) —
 * з уже перекладеною назвою: зміна мови міняє й заголовок. `null` — «назви
 * ще немає» (список вантажиться): лишається запасний «Wishlist».
 *
 * Заголовок не «залипає»: екран, що зникає, повертає запасний, а наступний
 * ставить свій (прибирання старого ефекту React виконує раніше, ніж ефект
 * нового екрана). Поки лінивий чанк їде, вкладка зветься «Wishlist».
 *
 * У заголовок потрапляє лише те, що сюди передали. Токен шеру, ключ гостя
 * чи адреса сторінки — ніколи (CLAUDE.md §3.5): заголовок осідає в історії
 * браузера й у перемикачі вкладок.
 */
export function useDocumentTitle(screen: string | null | undefined): void {
  const { t } = useI18n();
  const title = documentTitle(screen, t('app.name'));

  useEffect(() => {
    document.title = title;
  }, [title]);

  // Окремий ефект, щоб зміна назви на тому самому екрані (список довантажився)
  // не блимала запасним заголовком.
  useEffect(
    () => () => {
      document.title = APP_TITLE;
    },
    [],
  );
}
