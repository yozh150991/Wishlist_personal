-- Борг із ROADMAP: прибрати items_list_price_idx, якщо фільтр ціни без нього
-- не сповільниться.
--
-- Індекс (list_id, price, id) стоїть з першої міграції. Сортування за ціною
-- з ADR-017 іде за items_list_price_key_idx (list_id, coalesce(price, -1), id),
-- а фільтр «Ціна від–до» з ADR-050 застосовує клієнт до вже завантаженого
-- списку. Заміри list_items_page на 201 000 позицій (2001 список, найбільший —
-- 1000 позицій, межа імпорту), з фільтром ціни 300–900:
--
--   сортування за датою, великий список:  0,23 мс з індексом → 0,17 мс без;
--   сортування за ціною, великий список:  0,49 мс           → 0,20 мс;
--   сортування за датою, список зі 100:   0,10 мс           → 0,05 мс.
--
-- Без нього планувальник бере items_list_created_idx чи items_list_price_key_idx
-- і дофільтровує рядки одного списку — їх щонайбільше тисяча. Індекс лише
-- дорожчав кожен запис позиції.

drop index if exists public.items_list_price_idx;
