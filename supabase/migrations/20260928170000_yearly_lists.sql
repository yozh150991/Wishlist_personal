-- Щорічні свята (дизайн v2, крок 4в; потік U; ADR-047).
--
-- «Повторювати щороку» не створює нових списків саме: за місяць до
-- наступної дати v2 нагадує й веде в «Повторити на …» (S3) з уже
-- заповненим вибором. Для цього спискові досить однієї позначки.
--
-- Позначка належить одному списку з «ряду» — найсвіжішому. Коли список
-- повторюють, новий отримує позначку, а старий її втрачає (це робить
-- клієнт, `repeatList` у lib/db.ts). Так нагадування не приходить двічі і
-- не потрібне посилання списку на список.
--
-- Усталене `false` — поведінка v1, яка про щорічність не знає.

alter table public.lists
  add column repeats_yearly boolean not null default false;

comment on column public.lists.repeats_yearly is
  'Щорічне свято (ADR-047): за місяць до наступної дати v2 пропонує «Повторити на …». Нових списків база не створює.';
