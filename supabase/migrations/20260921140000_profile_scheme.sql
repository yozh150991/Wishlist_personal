-- 20260921140000_profile_scheme.sql
-- Кольорова схема інтерфейсу в профілі власника (ADR-031).
--
-- Схема й тема — дві незалежні осі: три схеми × (світла / темна / як у системі).
-- Тема вже має колонку `profiles.theme` з першої міграції; схема дістає таку
-- саму, щоб вибір переїжджав між пристроями, а не жив в одному браузері.
--
-- Гостя це не стосується: у нього акаунта немає, його вибір лишається в
-- localStorage і на сервер не їде. Відправляти його було б ще одним сигналом
-- про те, що хтось відкрив посилання, — а про гостей власник не дізнається
-- нічого (CLAUDE.md §3.2).

create type public.app_scheme as enum ('sage', 'slyva', 'vuhil');

comment on type public.app_scheme is
  'Кольорова схема інтерфейсу. Значення = data-scheme на <html>, набори токенів — app/src/styles/tokens.css.';

alter table public.profiles
  add column scheme public.app_scheme not null default 'sage';

comment on column public.profiles.scheme is
  'Усталена Шавлія. Читає й пише лише власник через наявні політики profiles_select_own / profiles_update_own.';

-- Нових політик не потрібно: `profiles` уже має RLS і дві політики на власника,
-- а `anon` відкликано разом з усією таблицею в 20260910120100_rls.sql. Нова
-- колонка успадковує їх — окремих грантів на колонку проєкт не використовує.
